public class Biodata {
    public static void main(String[] args) {

        // Menggunakan println()
        System.out.println("=================================");
        System.out.println("          BIODATA DIRI");
        System.out.println("=================================");
    

        // Menggunakan print()
        System.out.print("Nama       : ");
        System.out.println("Fatima Sahra");

        System.out.print("Alamat     : ");
        System.out.println("Pasangkayu");

        // Menggunakan printf()
        System.out.printf("Umur       : %d tahun%n", 19);
        System.out.printf("Jurusan    : %s%n", "Informatika");
        System.out.printf("Fakultas   : %s%n", "Teknik");

        System.out.println("=================================");
    }
}
