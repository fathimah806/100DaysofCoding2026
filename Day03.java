public class Day03 {
    public static void main(String[] args) {
        
        // \n = pindah ke baris baru
        System.out.println("Hallo\nDunia");

        // \t = membuat jarak/tab
        System.out.println("nama\tnilai");
        System.out.println("Andi\t90");

        // \" = menamppilkan ta da kutip
        System.out.println("\"Belajar Java\"");

        // \\ = menampilkan tanda backslash
        System.out.println("c\\Java");
    }
    
}
